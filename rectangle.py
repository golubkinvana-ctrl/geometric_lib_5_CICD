def area(a, b):
    '''

    Принимает стороны a и b, возвращает площадь прямоугольника.
    Пример: area(3, 4) ---> 12

    '''
    return a * b

def perimeter(a, b):
    '''

    Принимает стороны a и b, возвращает периметр прямоугольника.
    Пример: perimeter(3, 4) ---> 14

    '''
    return 2 * (a + b)