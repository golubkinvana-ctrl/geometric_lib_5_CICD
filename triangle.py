def area(a, h):
    '''

    Принимает сторону a и высоту h, возвращает площадь треугольника.
    Пример: area(4, 5) ---> 10.0

    '''
    return a * h / 2

def perimeter(a, b, c):
    '''

    Принимает стороны a, b, c, возвращает периметр треугольника.
    Пример: perimeter(3, 4, 6) ---> 13

    '''
    return a + b + c