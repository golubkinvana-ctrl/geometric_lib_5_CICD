import math

def area(r):
    '''

    Принимает радиус r, возвращает площадь круга данного радиуса.
    Пример: area(5) ---> 78.53981633974483

    '''
    return math.pi * r * r

def perimeter(r):
    '''

    Принимает радиус r, возвращает длину окружности данного радиуса.
    Пример: perimeter(5) ---> 31.41592653589793

    '''
    return 2 * math.pi * r
